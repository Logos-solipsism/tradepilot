"""离线评估的查询与相关性标签。

标签是怎么来的（**这条规则比标签本身重要**）：
写 relevance 时**只看商品标题的语义**，凭常识判断"这个商品是否满足这个查询"。
绝不允许先跑 BM25、看到排序结果再回头改标签——那样标签会贴合当前实现的缺陷，
评估集就退化成"给现状打满分"的橡皮图章，后续改检索时也就测不出任何变化。

分级：
- 2 = 完全满足（query 与标题语义一致，买了就对）
- 1 = 可接受（同类不同款、上位词/下位词、勉强能用）
- 0 = 不相关，**不写进 dict**（relevance 只记录 rel >= 1 的商品）

三组的用途（比例约 40 / 30 / 30）：
- "exact"：query 与标题用词基本重合。BM25 应当接近满分——它同时是**量尺自检**：
  这一组掉分，先怀疑评估集或分词坏了，而不是怀疑检索变差。
- "partial"：query 只覆盖标题的一部分词、或更短的词组（"跑鞋" / "键盘"）。
  考察部分匹配与类目内排序。
- "paraphrase"：同义改写、口语说法、上位词/下位词、错别字
  （"跑步用的鞋" / "隔绝外界噪音用的听歌设备" / "冲峰衣"）。
  这一组现在分数低是**预期结果，不是缺陷**——它是后续同义词泛化与向量召回要攻的目标。
  拿它当 KPI 时看的是相对提升，不是绝对值。

三道机械护栏（tests/test_eval_labels.py 按这个钉，口径见 app/eval/metrics.py 的
`char_coverage` 与 `LEXICAL_HIGH` / `LEXICAL_MID`）：

1. **paraphrase 禁止自证**：query 归一后不得是它任一期望标题的子串。
   反例（本护栏要防的东西）："降噪耳机" 标注期望 70 号，而 70 号标题逐字含
   "降噪耳机"——那已不是改写，是词面直配，拿到 R=1.000 却记进 paraphrase 组，
   直接把"语义改写能力"抬高。
2. **paraphrase 禁止高字面重合**：字符覆盖率必须 < LEXICAL_HIGH(0.7)。
   覆盖率 >= 0.7 的 query 靠词面匹配就能过，测不到语义泛化；留在组里只会稀释
   P5-4 同义泛化带来的增益（原本 8/30 条踩在这条线上，已按"保留期望 id、只换说法"改写）。
3. **exact 反向护栏**：exact 的字符覆盖率必须 >= LEXICAL_HIGH(0.7)。
   反过来若 exact 混进低重合的改写，两组就互相污染：exact 掉分到底是检索坏了还是
   评估集写错了，将无法区分。

这三条护栏存在的理由：**评估集自己也会腐化**。标签是手写的，最容易发生的退化不是
"检索变差"，而是"为了让分数好看去改标签"——把难 query 挪出 paraphrase、把期望 id
改小、把改写换成原词。护栏把这三类退化变成 pytest 里的一条红，而不是评审时的一句
"感觉不太对"。所以它钉的是评估集的**结构性质**，不是某一次的具体分数。

改写过的 paraphrase（保留期望 id 不变，只换说法）：
"降噪耳机"->"隔绝外界噪音用的听歌设备"、"蓝牙耳机"->"和手机无线相连的耳塞"、
"无线耳机"->"不用插线就能听歌的耳塞"、"跑步裤"->"晨跑时穿的速干裤子"、
"篮球鞋子"->"球场对抗时脚上穿的鞋子"、"拖地机器人"->"自己会擦地板的家电"、
"运动水杯"->"健身时补水用的容器"、"电脑充电器"->"给手提电脑补电的插头"。
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class EvalQuery:
    """一条评估查询；relevance 只含 rel >= 1 的商品 id。"""

    query: str
    group: str
    relevance: dict[int, int] = field(default_factory=dict)


def _q(query: str, group: str, relevance: dict[int, int]) -> EvalQuery:
    return EvalQuery(query=query, group=group, relevance=relevance)


